#!/usr/bin/env bash
# Worktree-isolated stacks. Each worktree gets its own k3d cluster
# (sealer-<hash>) and a block of host ports saved in .tools/dev-agent, so
# several stacks can run side by side without touching `atmos dev up`'s.
set -euo pipefail

command="${1:?Usage: agent.sh <up|down|destroy|status|env|logs> [tilt args]}"
shift
workspace="$(pwd -P)"
state_dir=.tools/dev-agent
state_file="${state_dir}/stack.env"
log_file="${state_dir}/tilt.log"
# one block of ports per stack, in this order from the block's base port
port_vars=(SEALER_TILT_PORT SEALER_CONTROL_PLANE_PORT SEALER_DYNAMODB_PORT SEALER_KMS_PORT SEALER_GITHUB_PORT)
block_size=10
block_count=800
first_port=16000
tilt_pid=""

fail() {
  echo "Error: $1" >&2
  if [[ -s "$log_file" ]]; then
    echo "--- last lines of ${log_file} ---" >&2
    tail -n 40 "$log_file" >&2
  fi
  exit 1
}

digest() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | awk '{print $1}'; else shasum -a 256 | awk '{print $1}'; fi
}

# ports saved by this repository's other worktrees stay theirs while stopped
reserved_ports() {
  local path
  while IFS= read -r path; do
    [[ "$(cd "$path" 2>/dev/null && pwd -P)" != "$workspace" && -f "${path}/${state_file}" ]] || continue
    sed -n 's/^SEALER_[A-Z_]*_PORT=//p' "${path}/${state_file}"
  done < <(git worktree list --porcelain 2>/dev/null | sed -n 's/^worktree //p')
}

block_free() {
  local base="$1" reserved="$2" offset port
  for offset in "${!port_vars[@]}"; do
    port=$((base + offset))
    grep -qx "$port" <<<"$reserved" && return 1
    lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1 && return 1
  done
  return 0
}

free_block() {
  local value="$1" reserved attempt base
  reserved="$(reserved_ports)"
  for ((attempt = 0; attempt < block_count; attempt++)); do
    base=$((first_port + ((value + attempt) % block_count) * block_size))
    if block_free "$base" "$reserved"; then
      echo "$base"
      return
    fi
  done
  fail "no free port block is available."
}

write_state() {
  local cluster="$1" base="$2" offset
  mkdir -p "$state_dir"
  {
    echo "# Generated by atmos dev agent. Delete with atmos dev agent destroy."
    echo "SEALER_CLUSTER=${cluster}"
    for offset in "${!port_vars[@]}"; do
      echo "${port_vars[$offset]}=$((base + offset))"
    done
  } >"$state_file"
}

load_state() {
  [[ -f "$state_file" ]] || fail "no agent stack is configured here. Run 'atmos dev agent up'."
  set -a
  # shellcheck disable=SC1090
  source "$state_file"
  set +a
  # shellcheck source=../lib/dev.sh
  source .atmos/scripts/lib/dev.sh
}

allocate_state() {
  local hash
  if [[ ! -f "$state_file" ]]; then
    hash="$(printf '%s' "$workspace" | digest)"
    write_state "sealer-${hash:0:8}" "$(free_block $((16#${hash:0:6})))"
  fi
  load_state
}

# ports are only forwarded while Tilt runs, so a stopped stack can move
reallocate_if_taken() {
  block_free "$SEALER_TILT_PORT" "$(reserved_ports)" && return
  echo "Ports saved for this stack are in use; moving it to a free port block." >&2
  write_state "$SEALER_CLUSTER" "$(free_block $(((SEALER_TILT_PORT - first_port) / block_size)))"
  load_state
}

tiltfile_field() {
  tilt get tiltfile '(Tiltfile)' --port "$SEALER_TILT_PORT" -o jsonpath="{${1}}" 2>/dev/null
}

tilt_running() {
  [[ "$(tiltfile_field .spec.path)" == "${workspace}/Tiltfile" ]]
}

start_tilt() {
  mkdir -p "$state_dir"
  echo "+ tilt up --context ${KUBE_CONTEXT} --port ${SEALER_TILT_PORT} $*" >&2
  # a session of its own keeps Tilt and its port forwards alive after this
  # command returns
  perl -MPOSIX -e 'POSIX::setsid(); exec @ARGV or die "exec: $!\n"' -- \
    tilt up --context "$KUBE_CONTEXT" --port "$SEALER_TILT_PORT" "$@" </dev/null >"$log_file" 2>&1 &
  tilt_pid="$!"
}

stop_tilt() {
  local pid
  tilt_running || return 0
  pid="$(lsof -t -nP -iTCP:"$SEALER_TILT_PORT" -sTCP:LISTEN 2>/dev/null | head -n 1)"
  [[ -n "$pid" ]] || return 0
  echo "Stopping Tilt (pid ${pid})." >&2
  kill "$pid" 2>/dev/null || return 0
  for _ in $(seq 1 40); do
    kill -0 "$pid" 2>/dev/null || return 0
    sleep 0.25
  done
  kill -9 "$pid" 2>/dev/null || true
}

resource_rows() {
  tilt get uiresources --port "$SEALER_TILT_PORT" -o jsonpath='{range .items[*]}{.metadata.name}{"\t"}{.status.disableStatus.state}{"\t"}{.status.conditions[?(@.type=="Ready")].status}{"\t"}{.status.updateStatus}{"\t"}{.status.runtimeStatus}{"\n"}{end}' 2>/dev/null
}

wait_ready() {
  local deadline=$((SECONDS + timeout)) error rows pending="the Tiltfile"
  echo "Waiting for ${SEALER_CLUSTER} to become ready. Tilt log: ${log_file}" >&2
  while ((SECONDS < deadline)); do
    if [[ -n "$tilt_pid" ]] && ! kill -0 "$tilt_pid" 2>/dev/null; then
      fail "Tilt exited before the stack was ready."
    fi
    if [[ -n "$(tiltfile_field .status.terminated.finishedAt || true)" ]]; then
      error="$(tiltfile_field .status.terminated.error || true)"
      [[ -z "$error" ]] || fail "the Tiltfile failed to load: ${error}"
      rows="$(resource_rows || true)"
      pending="$(awk -F'\t' '$1 != "(Tiltfile)" && $2 != "Disabled" && $3 != "True" { printf "%s ", $1 }' <<<"$rows")"
      [[ -n "$rows" && -z "$pending" ]] && return 0
    fi
    sleep 2
  done
  fail "timed out after ${timeout}s waiting for: ${pending}. Tilt is still running; see 'atmos dev agent status'."
}

print_endpoints() {
  cat >&2 <<EOF
  Cluster:        ${SEALER_CLUSTER} (context ${KUBE_CONTEXT})
  Tilt:           http://localhost:${SEALER_TILT_PORT}
  Web UI:         http://localhost:${SEALER_CONTROL_PLANE_PORT}
  DynamoDB Local: http://localhost:${SEALER_DYNAMODB_PORT}
  KMS (local):    http://localhost:${SEALER_KMS_PORT}
  GitHub (mock):  http://localhost:${SEALER_GITHUB_PORT}
EOF
}

case "$command" in
  up)
    timeout="${DEV_TIMEOUT:-600}"
    [[ "$timeout" =~ ^[0-9]+$ ]] || fail "--timeout must be a whole number of seconds."
    allocate_state
    if ! tilt_running; then
      reallocate_if_taken
      ensure_cluster
      pull_charts
      build_web
      build_binaries
      start_tilt "$@"
    fi
    wait_ready
    echo >&2
    echo "Agent stack is ready." >&2
    print_endpoints
    echo >&2
    echo "For other commands against this stack: eval \"\$(atmos dev agent env)\"" >&2
    ;;
  down)
    load_state
    stop_tilt
    if ! cluster_exists; then
      echo "This worktree's cluster does not exist; nothing to take down." >&2
      exit 0
    fi
    k3d cluster start "$SEALER_CLUSTER" >/dev/null
    pull_charts
    exec tilt down --context "$KUBE_CONTEXT"
    ;;
  destroy)
    load_state
    if [[ "${DEV_YES:-}" != "true" ]]; then
      printf 'This deletes the k3d cluster %s and its data. Continue? [y/N] ' "$SEALER_CLUSTER" >&2
      read -r answer
      [[ "$answer" =~ ^[Yy]$ ]] || exit 0
    fi
    stop_tilt
    delete_cluster
    rm -rf "$state_dir"
    echo "Removed agent stack ${SEALER_CLUSTER}." >&2
    ;;
  status)
    load_state
    if tilt_running; then
      {
        printf 'RESOURCE\tUPDATE\tRUNTIME\tREADY\n'
        resource_rows | awk -F'\t' '$1 != "(Tiltfile)" && $2 != "Disabled" { printf "%s\t%s\t%s\t%s\n", $1, $4, $5, ($3 == "" ? "False" : $3) }' | sort
      } | column -t -s $'\t' >&2
    else
      echo "Tilt is not running. Start it with 'atmos dev agent up'." >&2
    fi
    echo >&2
    print_endpoints
    ;;
  env)
    load_state
    echo "export SEALER_CLUSTER=${SEALER_CLUSTER}"
    for var in "${port_vars[@]}"; do
      echo "export ${var}=${!var}"
    done
    ;;
  logs)
    load_state
    tilt_running || fail "Tilt is not running for this worktree. Run 'atmos dev agent up'."
    args=(logs --port "$SEALER_TILT_PORT")
    [[ "${DEV_FOLLOW:-}" == "true" ]] && args+=(--follow)
    [[ -n "${DEV_RESOURCE:-}" ]] && args+=("$DEV_RESOURCE")
    exec tilt "${args[@]}"
    ;;
  *)
    fail "unknown agent command '${command}'."
    ;;
esac
